import tensorflow as tf
from tensorflow.keras import datasets, layers, models, regularizers
import matplotlib.pyplot as plt
import numpy as np

print(f"TensorFlow version: {tf.__version__}")

# Using CIFAR-10 dataset
# CIFAR-10 SIZE = 60,000 32x32 color images in 10 classes,
# Each class has 6,000 images.
# Training Dataset 50,000
# Test dataset 10,000
(train_images, train_labels), (test_images, test_labels) = datasets.cifar10.load_data()

# Normalize pixel values to be between 0 and 1
train_images, test_images = train_images / 255.0, test_images / 255.0

# Classes in CIFAR-10
class_names = ['airplane', 'automobile', 'bird', 'cat', 'deer', 'dog', 'frog', 'horse', 'ship', 'truck']

# Showing some random images
plt.figure(figsize=(10, 10))
for i in range(25):
    plt.subplot(5, 5, i+1)
    plt.xticks([])
    plt.yticks([])
    plt.grid(False)
    plt.imshow(train_images[i])
    # The CIFAR labels are arrays, e.g., [9]. We need to access the scalar value.
    plt.xlabel(class_names[train_labels[i][0]])
plt.suptitle("CIFAR-10 Images")
plt.show()

# --- 2. Define the CNN model architecture ---
# Initilizing a Sequential model
model = models.Sequential()

# First Convolutional Block
# Conv2D layer with 32 filters, each 3x3.
# 'activation='relu'' applies the Rectified Linear Unit activation function.
# 'input_shape=(32, 32, 3)' specifies the input dimensions for the first layer:
# 32x32 pixels, with 3 color channels (RGB).
model.add(layers.Conv2D(32, (3, 3), activation='relu', input_shape=(32, 32, 3)))
# MaxPooling2D layer reduces the spatial dimensions (height and width) by taking the maximum
# value over a 2x2 window. This helps in reducing computation and extracting dominant features.
model.add(layers.MaxPooling2D((2, 2)))

# Second Convolutional Block
# Another Conv2D layer with 64 filters. As the network deepens, filters often increase.
model.add(layers.Conv2D(64, (3, 3), activation='relu'))
model.add(layers.MaxPooling2D((2, 2)))

# Third Convolutional Block
model.add(layers.Conv2D(64, (3, 3), activation='relu'))
# IMPORTANT: WE CAN ADD Another MaxPooling2D ,
# but often it's omitted
# after the last convolutional block before flattening.

# Flatten the output of the convolutional and pooling layers
# This layer flattens the 2D feature maps into a 1D vector so it can be fed into
# the fully connected (Dense) layers.
model.add(layers.Flatten())

# Fully Connected Layers (Dense layers for classification)
# Dense layer with 64 neurons and ReLU activation.
# These layers are similar to those in traditional ANNs and perform the final classification.
model.add(layers.Dense(64, activation='relu'))
# Output Dense layer with 10 neurons (one for each CIFAR-10 class).
# 'activation='softmax'' ensures the output is a probability distribution over the 10 classes,
# summing to 1. The class with the highest probability is the predicted class.
model.add(layers.Dense(10, activation='softmax'))


model.summary()

# --- 3. Compile the model ---
# Optimizer: 'adam' is a popular and effective optimization algorithm.
# Loss function: 'sparse_categorical_crossentropy' is used because our labels are integers
# (e.g., 0, 1, ..., 9) and not one-hot encoded. If labels were one-hot encoded (e.g., [0,0,1,0...]),
# 'categorical_crossentropy' would be used.

model.compile(optimizer='adam',
              loss='sparse_categorical_crossentropy',
              metrics=['accuracy'])

# --- 4. Train the model ---

history = model.fit(train_images, train_labels, epochs=10,
                    validation_data=(test_images, test_labels))

# --- 5. Evaluate the model ---
print("\n--- Evaluating the model on the test dataset ---")
test_loss, test_acc = model.evaluate(test_images,  test_labels, verbose=2)
print(f"Test accuracy: {test_acc}")
print(f"Test loss: {test_loss}")

# --- 6. Visualize training history (Accuracy and Loss) ---
plt.figure(figsize=(12, 4))

# Plot training & validation accuracy values
plt.subplot(1, 2, 1)
plt.plot(history.history['accuracy'], label='Accuracy')
plt.plot(history.history['val_accuracy'], label='Validation Accuracy')
plt.title('Model Accuracy')
plt.xlabel('Epoch')
plt.ylabel('Accuracy')
plt.legend(loc='lower right')
plt.grid(True)

# Plot training & validation loss values
plt.subplot(1, 2, 2)
plt.plot(history.history['loss'], label='Loss')
plt.plot(history.history['val_loss'], label='Validation Loss')
plt.title('Model Loss')
plt.xlabel('Epoch')
plt.ylabel('Loss')
plt.legend(loc='upper right')
plt.grid(True)

plt.tight_layout()
plt.show()


print("\n--- Making predictions on a few test images ---")

# Select a few images from the test set for prediction
num_predictions_to_show = 5
sample_indices = np.random.choice(len(test_images), num_predictions_to_show, replace=False)

plt.figure(figsize=(12, 6))
for i, idx in enumerate(sample_indices):
    img = test_images[idx]
    true_label = test_labels[idx][0] # Access scalar label

    # Add batch dimension for prediction (model expects batch of images)
    img_batch = np.expand_dims(img, axis=0)
    predictions = model.predict(img_batch)
    predicted_label = np.argmax(predictions[0])

    plt.subplot(1, num_predictions_to_show, i + 1)
    plt.xticks([])
    plt.yticks([])
    plt.grid(False)
    plt.imshow(img)

    color = 'green' if predicted_label == true_label else 'red'
    plt.xlabel(f"True: {class_names[true_label]}\nPred: {class_names[predicted_label]}", color=color)

plt.suptitle("Sample Predictions (Green: Correct, Red: Incorrect)")
plt.tight_layout()
plt.show()

print("\nCNN implementation complete. Model trained and evaluated on CIFAR-10.")